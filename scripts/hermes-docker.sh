#!/usr/bin/env bash
# HomeHub's server Hermes in Docker (agents/hermes/docker/docker-compose.yml).
#   scripts/hermes-docker.sh up       prepare ~/.hermes-homehub, start Hermes + tunnel, point production at it
#   scripts/hermes-docker.sh status   container state, tunnel URL, health
#   scripts/hermes-docker.sh logs     follow Hermes logs
#   scripts/hermes-docker.sh down     stop the stack (production then reports the server assistant as unreachable)
# Secrets come from Secret Manager (project alias "prod") and are written only to the 0600 .env in the data folder.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export HOMEHUB_HERMES_HOME="${HOMEHUB_HERMES_HOME:-$HOME/.hermes-homehub}"
export HERMES_UID="$(id -u)" HERMES_GID="$(id -g)"
COMPOSE=(docker compose -f "$ROOT/agents/hermes/docker/docker-compose.yml")
FUNCS_ENV="$ROOT/backend/firebase/functions/.env.your-firebase-project-id"
MCP_URL="https://asia-south1-your-firebase-project-id.cloudfunctions.net/mcp"
IMAGE="homehub-hermes:v0.21.2-5eb99eb2"
source "$ROOT/scripts/dev-env.sh" >/dev/null

secret() { (cd "$ROOT/backend/firebase" && firebase functions:secrets:access "$1" --project prod 2>/dev/null) || true; }
PUBLIC_URL="${HOMEHUB_PUBLIC_URL:-https://hermes.example.com}"
set_env() { # set_env KEY VALUE in the Functions env file
  if grep -q "^$1=" "$FUNCS_ENV"; then sed -i '' "s#^$1=.*#$1=$2#" "$FUNCS_ENV"; else printf '%s=%s\n' "$1" "$2" >> "$FUNCS_ENV"; fi
}

prepare() {
  local H="$HOMEHUB_HERMES_HOME"
  mkdir -p "$H/skills"
  for s in "$ROOT"/agents/hermes/skills/*/; do rm -rf "$H/skills/$(basename "$s")"; cp -R "$s" "$H/skills/"; done
  cp "$ROOT/agents/hermes/profiles/homehub-hermes/SOUL.md" "$H/SOUL.md"
  { cat "$ROOT/agents/hermes/config/config.yaml"; cat <<'YAML'

# Docker runtime defaults (added by scripts/hermes-docker.sh). HomeHub sends model/provider per run.
model:
  provider: openrouter
  default: google/gemini-2.5-flash
  api_mode: chat_completions

# When the primary model is rate-limited or erroring (e.g. provider 429), switch to another provider's model.
fallback_providers:
  - provider: openrouter
    model: google/gemma-4-31b-it:free
YAML
  } > "$H/config.yaml"

  if [[ ! -f "$H/.env" ]]; then
    local key; key="$(secret HERMES_API_KEY)"
    if [[ -z "$key" || "$key" == "unset" ]]; then
      key="$(openssl rand -hex 32)"
      printf '%s' "$key" | (cd "$ROOT/backend/firebase" && firebase functions:secrets:set HERMES_API_KEY --data-file - --project prod --force >/dev/null)
      echo "Generated HERMES_API_KEY and stored it in Secret Manager."
    fi
    umask 077
    cat > "$H/.env" <<EOF
# HomeHub server Hermes — generated by scripts/hermes-docker.sh. Private (0600).
API_SERVER_ENABLED=true
API_SERVER_HOST=0.0.0.0
API_SERVER_PORT=8642
API_SERVER_KEY=$key
HOMEHUB_MCP_URL=$MCP_URL
HOMEHUB_MCP_SERVICE_KEY=$(secret HOMEHUB_MCP_SERVICE_KEY)
OPENROUTER_API_KEY=$(secret MODEL_API_KEY)
EOF
    chmod 600 "$H/.env"
  fi
  echo "Data folder ready: $H"
}

wait_healthy() { # wait_healthy URL
  for _ in $(seq 1 60); do
    curl -fsS --max-time 5 "$1/health" >/dev/null 2>&1 && return 0
    sleep 3
  done
  return 1
}

up() {
  docker image inspect "$IMAGE" >/dev/null 2>&1 || { echo "Image $IMAGE missing — build it: docker build -t $IMAGE ~/.hermes/hermes-agent (at commit 5eb99eb2)"; exit 1; }
  [[ -f "$HOMEHUB_HERMES_HOME/cloudflared/config.yml" && -f "$HOMEHUB_HERMES_HOME/cloudflared/credentials.json" ]] || {
    cat <<EOT
The Cloudflare tunnel isn't set up yet. One time (needs your Cloudflare login, \`cloudflared tunnel login\`):
  cloudflared tunnel create homehub
  cloudflared tunnel route dns --overwrite-dns <tunnel-uuid> ${PUBLIC_URL#https://}
  mkdir -p $HOMEHUB_HERMES_HOME/cloudflared && cp ~/.cloudflared/<tunnel-uuid>.json $HOMEHUB_HERMES_HOME/cloudflared/credentials.json
  # and write $HOMEHUB_HERMES_HOME/cloudflared/config.yml (see docs/hermes-setup.md)
EOT
    exit 1; }
  prepare
  "${COMPOSE[@]}" up -d
  wait_healthy "http://127.0.0.1:8652" || { echo "Hermes didn't become healthy — scripts/hermes-docker.sh logs"; exit 1; }
  echo "Hermes healthy on 127.0.0.1:8652"
  local url="$PUBLIC_URL"
  wait_healthy "$url" || { echo "$url isn't reachable yet — check: docker logs homehub-hermes-tunnel"; exit 1; }
  echo "Public URL: $url"

  local current; current="$(grep '^HERMES_API_URL=' "$FUNCS_ENV" | cut -d= -f2- || true)"
  set_env HERMES_PROVIDER_SIMPLE openrouter;  set_env HERMES_MODEL_SIMPLE google/gemini-2.5-flash-lite
  set_env HERMES_PROVIDER_COMPLEX openrouter; set_env HERMES_MODEL_COMPLEX google/gemini-2.5-flash
  if [[ "$current" != "$url" || "${FORCE_DEPLOY:-}" == 1 ]]; then
    set_env HERMES_API_URL "$url"
    echo "Pointing production at the new URL (redeploying api + scheduler)…"
    (cd "$ROOT/backend/firebase" && firebase deploy --only functions:homehub:api,functions:homehub:scheduler --project prod --non-interactive --force | grep -E "Successful|Error|complete")
  else
    echo "Production already points at this URL."
  fi
}

case "${1:-}" in
  up) up ;;
  status)
    "${COMPOSE[@]}" ps
    echo "Public URL: $PUBLIC_URL ($(curl -s -o /dev/null -w '%{http_code}' --max-time 8 "$PUBLIC_URL/health"))"
    curl -fsS --max-time 5 http://127.0.0.1:8652/health >/dev/null && echo "Local Hermes: healthy"
    echo "Production HERMES_API_URL: $(grep '^HERMES_API_URL=' "$FUNCS_ENV" | cut -d= -f2-)" ;;
  logs) "${COMPOSE[@]}" logs -f hermes ;;
  down) "${COMPOSE[@]}" down ;;
  *) echo "usage: $0 up|status|logs|down" >&2; exit 2 ;;
esac
